@app.post("/api/tts")
def api_tts(req: TtsRequest):
    """把村寨代言人的回答合成为语音，返回音频。"""
    text = req.text.strip()
    village = req.village
    gender = req.gender or VILLAGE_GENDERS.get(village, "female")
    accent = req.accent or "mandarin"

    if not text:
        return JSONResponse({"error": "文本不能为空"}, status_code=400)

    result = synthesize_speech(text, gender=gender, accent=accent)
    if not result:
        return JSONResponse({"error": "语音合成暂不可用，请稍后重试"}, status_code=503)

    audio_bytes, voice, mime = result
    return Response(
        content=audio_bytes,
        media_type=mime,
        headers={
            "X-Voice": voice,
            "Cache-Control": "no-store",
        },
    )


