@app.post("/chat")
def chat(req: ChatRequest, authorization: str = Header(default="")):
    """对话接口"""
    question = req.question
    if not question:
        return JSONResponse({"error": "问题不能为空"}, status_code=400)

    try:
        user_id = get_current_username(authorization)
        answer = agent.ask(question, village=req.village, user_id=user_id, persona_mode=req.mode)
        profile = agent.memory_store.get_profile(user_id) if user_id else None
        return {
            "village": req.village,
            "answer": answer,
            "mode": agent.current_persona_mode,
            "profile": profile,
            "plan": agent.last_plan,
            "tool_results": agent.last_tool_results,
            "evidence": agent.last_evidence,
            "verification": agent.last_verification,
        }
    except Exception as e:
        return JSONResponse({"error": str(e)}, status_code=500)


class ChatCompareRequest(BaseModel):
    village: str = "皎平渡"
    question: str = ""


@app.post("/api/chat/compare")
def api_chat_compare(req: ChatCompareRequest, authorization: str = Header(default="")):
    """同一问题用三种讲解模式各生成一份回答，便于并排对照演示。"""
    question = (req.question or "").strip()
    if not question:
        return JSONResponse({"error": "问题不能为空"}, status_code=400)
    user_id = get_current_username(authorization)

    answers = {}
    for mode in ("student", "tourist", "researcher"):
        try:
            answers[mode] = agent.ask(
                question, village=req.village or "皎平渡",
                user_id=user_id, persona_mode=mode, remember=False,
            )
        except Exception as e:
            answers[mode] = "（%s 模式生成失败：%s）" % (mode, e)
    return {"village": req.village, "question": question, "answers": answers}


@app.get("/api/villages")
def get_villages():
    """返回村寨列表（含坐标、年份、所属队伍）"""
    villages = []
    seen = set()
    seen_coords = set()
    for name in config.VILLAGES:
        if name in seen or name not in VILLAGE_COORDS:
            continue
        c = VILLAGE_COORDS[name]
        coord = (round(c["lat"], 2), round(c["lng"], 2))
        if coord in seen_coords:
            continue
        seen.add(name)
        seen_coords.add(coord)
        villages.append({
            "name": name,
            "lat": c["lat"],
            "lng": c["lng"],
            "city": c["city"],
            "event": c["event"],
            "year": c["year"],
            "army": c["army"],
            "avatar": "/static/avatars/" + VILLAGE_AVATARS.get(name, "zaxi") + ".png",
            "voice_gender": VILLAGE_GENDERS.get(name, "female"),
        })
    return villages


