def apply_fixes(text: str, fixes: Iterable[Tuple[str, str]] = OCR_FIXES) -> str:
    """
    按"错误串长度降序"应用纠错替换，多轮迭代直到稳定（fixpoint）。
    长串优先保证组合错字（如"巧度金沙江"）先被替换；一轮替换可能
    产生新的可匹配长串（如"巧度金小江"先变"巧度金沙江"再变"巧渡金沙江"），
    因此迭代至无变化为止，最多 10 轮防死循环。
    """
    ordered = sorted(fixes, key=lambda x: len(x[0]), reverse=True)
    for _ in range(10):
        changed = False
        for wrong, right in ordered:
            if not wrong or wrong == right:
                continue
            if wrong in text:
                text = text.replace(wrong, right)
                changed = True
        if not changed:
            break
    return text


